// Modulo 2 - Variables

// let: se usa para variables que pueden cambiar de valor
// const: se usa para valores que no cambian, no se pueden reasignar
// var: es la forma antigua de declarar variables, hoy se usa mas let

// ===== Ejercicio 1 =====
let ciudad = "Madrid";
let poblacion = 3300000;
let esCapital = true;
console.log(ciudad, poblacion, esCapital);

// ===== Ejercicio 2 =====
let animal = "perro";
let raza = "Labrador";
let edadAnimal = 5;
console.log("Mi " + animal + " es un " + raza + " de " + edadAnimal + " años.");

// ===== Ejercicio 3 =====
let num1 = 10;
let num2 = 5;
let suma = num1 + num2;
let resta = num1 - num2;
console.log("Suma:", suma, "Resta:", resta);

// ===== Ejercicio 4 =====
let nombreProducto = "Laptop";
let precio = 1200;
let disponible = true;

console.log("Producto:", nombreProducto);
console.log("Precio:", precio);
console.log("¿Está disponible?", disponible);

// ===== Ejercicio 5 =====
let marcaCoche = "Toyota";
let modelo = "Corolla";
let año = 2020;

console.log("Marca: " + marcaCoche);
console.log("Modelo: " + modelo);
console.log("Año: " + año);
console.log("Vehículo:", marcaCoche, modelo, año);
