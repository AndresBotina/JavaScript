// Ejercicio 1. Operaciones aritméticas básicas
// Elabore un algoritmo que, dados dos números, calcule y muestre su suma,
// resta, multiplicación y división.
// Datos de prueba: Número 1 = 10, Número 2 = 5

let numero1 = 10;
let numero2 = 5;

let suma = numero1 + numero2;
let resta = numero1 - numero2;
let multiplicacion = numero1 * numero2;
let division = numero1 / numero2;

console.log(`Suma: ${numero1} + ${numero2} = ${suma}
Resta: ${numero1} - ${numero2} = ${resta}
Multiplicación: ${numero1} * ${numero2} = ${multiplicacion}
División: ${numero1} / ${numero2} = ${division}`);
