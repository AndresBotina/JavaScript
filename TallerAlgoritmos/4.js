// Ejercicio 4. Velocidad de un móvil
// Un vehículo recorre cierta distancia en un tiempo determinado. Calcule la
// velocidad a la que se desplazó.
// Datos de prueba: Distancia = 20 km, Tiempo = 3 horas

let distancia = 20;
let tiempo = 3;

let velocidad = distancia / tiempo;

console.log(`Distancia: ${distancia} km`);
console.log(`Tiempo: ${tiempo} horas`);
console.log(`Velocidad: ${velocidad.toFixed(2)} km/h`);
